function renderProducts() {
  if (!elements.productGrid) return;

  elements.productGrid.replaceChildren();

  ["Sweatshirts","Jackets"].forEach(category => {
    elements.productGrid.appendChild(
      makeElement("h3","catalogue-category",category)
    );

 PRODUCTS
  .filter(p => p.category === category)
  .sort((a, b) => {
    if (a.price === null) return 1;
    if (b.price === null) return -1;
    return a.price - b.price;
  })
  .forEach(product => {
    elements.productGrid.appendChild(
      createProductCard(product)
    );
  });
  });
}

function createSelectGroup(labelText,id,values) {
  const group = makeElement("div","option-group");
  const label = makeElement("label","",labelText);
  label.htmlFor = id;

  const select = document.createElement("select");
  select.id = id;

  values.forEach(value => {
    const option = new Option(value,value);
    select.add(option);
  });

  group.append(label,select);
  return {group,select};
}

function createProductCard(product) {
  const card = makeElement("article","product-card");
  const imageBox = makeElement("div","product-image");

  const images = getProductImages(product);

  function showPlaceholder() {
    imageBox.replaceChildren(
      makeElement("div","product-placeholder",product.name)
    );
  }

  if (images.length) {
    const imageButton = makeElement(
      "button","product-image-button"
    );
    imageButton.type = "button";
    imageButton.setAttribute(
      "aria-label",`Enlarge image of ${product.name}`
    );
    imageButton.title = "Click to enlarge image";

    const image = document.createElement("img");
    image.src = images[0].src;
    image.alt = product.name;
    image.loading = "lazy";

    image.onerror = showPlaceholder;

    const zoom = makeElement(
      "span","product-zoom-label","View larger"
    );
    zoom.setAttribute("aria-hidden","true");

    imageButton.append(image,zoom);
    imageButton.addEventListener("click",() => {
      openGallery(product,0);
    });

    imageBox.appendChild(imageButton);
  } else {
    showPlaceholder();
  }

  const details = makeElement("div","product-details");
  const title = makeElement("h3","product-title",product.name);
  const sku = makeElement(
    "p","product-sku",`Item #${product.sku}`
  );
  const description = makeElement(
    "p","product-description",product.description
  );
  const price = makeElement(
    "p","product-price",formatPrice(product.price)
  );
  const priceNote = makeElement(
    "p","product-price-note",
    product.price === null
      ? "Supplier pricing to be confirmed."
      : "Historical supplier quote, before tax. Final pricing subject to confirmation."
  );

  const colour = createSelectGroup(
    "Colour",`colour-${product.id}`,product.colours
  );
  const size = createSelectGroup(
    "Size",`size-${product.id}`,product.sizes
  );

  const quantityGroup = makeElement("div","option-group");
  const quantityLabel = makeElement("label","","Quantity");
  quantityLabel.htmlFor = `quantity-${product.id}`;

  const quantityInput = document.createElement("input");
  quantityInput.type = "number";
  quantityInput.id = `quantity-${product.id}`;
  quantityInput.min = "1";
  quantityInput.max = "99";
  quantityInput.step = "1";
  quantityInput.value = "1";

  quantityGroup.append(quantityLabel,quantityInput);

  const options = makeElement("div","product-options");
  options.append(colour.group,size.group,quantityGroup);

  const swatchRow = makeElement("div","product-swatch-row");
  const swatch = makeElement("span","product-colour-swatch");
  const colourText = makeElement("span","product-colour-name");

  function updateSwatch() {
    const value = colour.select.value;
    swatch.style.backgroundColor =
      COLOUR_HEX[value] || "#cccccc";
    colourText.textContent = value;
  }

  colour.select.addEventListener("change",updateSwatch);
  updateSwatch();
  swatchRow.append(swatch,colourText);

  const button = makeElement(
    "button","button button-primary","Add to Request"
  );
  button.type = "button";

  button.addEventListener("click",() => {
    const quantity = Number(quantityInput.value);

    if (!Number.isInteger(quantity) ||
        quantity < 1 || quantity > 99) {
      quantityInput.setCustomValidity(
        "Enter a whole number from 1 to 99."
      );
      quantityInput.reportValidity();
      return;
    }

    quantityInput.setCustomValidity("");

    addToCart({
      productId:product.id,
      colour:colour.select.value,
      size:size.select.value,
      quantity
    });

    quantityInput.value = "1";
    openCart();
  });

  quantityInput.addEventListener("input",() => {
    quantityInput.setCustomValidity("");
  });

  details.append(
    title,sku,description,price,priceNote,
    options,swatchRow
  );

  if (product.sizeStatus === "provisional") {
    details.appendChild(makeElement(
      "p","product-price-note",
      "Size availability to be confirmed."
    ));
  }

  details.appendChild(button);
  card.append(imageBox,details);
  return card;
}

